/** Urutan tabel sesuai ketergantungan kunci asing (untuk cadangan & migrasi). */
export const TABEL = ['pengaturan', 'sekolah', 'wilayah_lokal', 'pengguna', 'mapel', 'kategori', 'soal', 'ujian_massal', 'ujian',
  'peserta_ujian', 'jawaban', 'feedback', 'pengajuan_akun'];

// migrasi ringan untuk database V3 yang sudah ada: tambah kolom baru bila belum ada
const KOLOM_TAMBAHAN = [
  ['sekolah', 'stempel_url', 'TEXT'], ['sekolah', 'telepon', 'TEXT'], ['sekolah', 'email', 'TEXT'], ['sekolah', 'kota_ttd', 'TEXT'],
];

export async function siapkanSkema() {
  // beberapa instans aplikasi bisa menyala bersamaan: kunci agar skema dibuat sekali
  await tx(async () => {
    await query('SELECT pg_advisory_xact_lock(20262026)');
    await query(SKEMA);
    for (const [t, c, def] of KOLOM_TAMBAHAN) await query(`ALTER TABLE ${t} ADD COLUMN IF NOT EXISTS ${c} ${def}`);
  });
  await muatPengaturan();
}

/** Setel ulang urutan id setelah impor baris dengan id eksplisit. */
export async function setelUrutanId() {
  for (const t of TABEL) {
    const ada = await one(`SELECT 1 FROM information_schema.columns WHERE table_name = ? AND column_name = 'id'`, t);
    if (ada) await query(`SELECT setval(pg_get_serial_sequence('${t}', 'id'), COALESCE((SELECT MAX(id) FROM ${t}), 0) + 1, false)`);
  }
}

export async function kolomTabel(t) {
  return (await all(`SELECT column_name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position`, t))
    .map((r) => r.column_name);
}

/** Sisipkan banyak baris sekaligus (dipecah agar tidak melewati batas parameter). */
export async function sisipkanBanyak(t, cols, rows) {
  if (!rows.length) return;
  const per = Math.max(1, Math.floor(30000 / cols.length));
  for (let i = 0; i < rows.length; i += per) {
    const part = rows.slice(i, i + per);
    const params = [];
    const vals = part.map((r) => `(${cols.map((c) => { params.push(r[c] === undefined ? null : r[c]); return `$${params.length}`; }).join(',')})`);
    await runner().query(`INSERT INTO ${t} (${cols.map((c) => `"${c}"`).join(',')}) VALUES ${vals.join(',')}`, params);
  }
}

// ---------- pengaturan (disimpan di memori, disegarkan lewat Redis bila berubah di instans lain) ----------
const pengaturan = new Map();
let onSettingChange = null;
export const saatPengaturanBerubah = (fn) => { onSettingChange = fn; };

export async function muatPengaturan() {
  const rows = await all('SELECT kunci, nilai FROM pengaturan');
  pengaturan.clear();
  for (const r of rows) {
    try { pengaturan.set(r.kunci, JSON.parse(r.nilai)); } catch { /* abaikan nilai rusak */ }
  }
}

export function setting(kunci, fallback = null) {
  return pengaturan.has(kunci) ? pengaturan.get(kunci) : fallback;
}
export async function setSetting(kunci, nilai) {
  await run('INSERT INTO pengaturan (kunci, nilai) VALUES (?, ?) ON CONFLICT (kunci) DO UPDATE SET nilai = excluded.nilai', kunci, JSON.stringify(nilai));
  pengaturan.set(kunci, nilai);
  onSettingChange?.(kunci);
}
