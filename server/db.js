const DATABASE_URL = process.env.DATABASE_URL || 'postgres://tka:tka@127.0.0.1:5432/tka';
export const pool = new pg.Pool({
  connectionString: DATABASE_URL,
  max: Number(process.env.PG_POOL_MAX || 20),
  idleTimeoutMillis: 30e3,
  connectionTimeoutMillis: 10e3,
  // PgBouncer mode transaksi: tanpa prepared statement bernama, tanpa SET sesi
  application_name: 'tka2026',
});
pool.on('error', (e) => console.error('Koneksi PostgreSQL bermasalah:', e.message));

const txStore = new AsyncLocalStorage();

/** Ubah placeholder `?` gaya lama menjadi `$1, $2, …` (mengabaikan teks di dalam tanda kutip). */
const cacheSql = new Map();
export function toPg(sql) {
  let out = cacheSql.get(sql);
  if (out) return out;
  let n = 0, q = null;
  out = '';
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (q) { out += c; if (c === q) q = null; continue; }
    if (c === "'" || c === '"') { q = c; out += c; continue; }
    if (c === '?') { out += `$${++n}`; continue; }
    out += c;
  }
  if (cacheSql.size > 2000) cacheSql.clear();
  cacheSql.set(sql, out);
  return out;
}

const runner = () => txStore.getStore() || pool;

export async function query(sql, params = []) {
  return runner().query(toPg(sql), params);
}
export const one = async (sql, ...p) => (await query(sql, p)).rows[0];
export const all = async (sql, ...p) => (await query(sql, p)).rows;
export const run = async (sql, ...p) => { const r = await query(sql, p); return { changes: r.rowCount }; };
/** INSERT … lalu kembalikan id baris baru. */
export const insertId = async (sql, ...p) => Number((await query(`${sql} RETURNING id`, p)).rows[0].id);

/** Jalankan fn di dalam satu transaksi; kueri di dalamnya otomatis memakai koneksi yang sama. */
export async function tx(fn) {
  if (txStore.getStore()) return fn(); // transaksi bersarang ikut transaksi luar
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const r = await txStore.run(client, fn);
    await client.query('COMMIT');
    return r;
  } catch (e) {
    try { await client.query('ROLLBACK'); } catch { /* koneksi putus */ }
    throw e;
  } finally {
    client.release();
  }
}

